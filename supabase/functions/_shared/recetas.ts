  region: Region | null; // de qué parte del Perú es, si es peruana
  dieta: Dieta;
  conGluten: boolean;
  conLactosa: boolean;
  requiere: string[]; // ids de ELECTRODOMESTICOS sin los que no se puede hacer
  dificultad: 1 | 2 | 3; // 1: para alguien que recién empieza
  ingredienteIcono: string; // id de INGREDIENTES, para mostrar su ícono
